export interface SixWeekTemplate {
  id: string;
  level: ReportRating;
  title: string;
  text: string;
}

export const TEMPLATE_LEVELS: { id: ReportRating; label: string }[] = [
  { id: 'excellent', label: 'ممتاز' },
  { id: 'very_good', label: 'جيد جداً' },
  { id: 'good', label: 'جيد' },
  { id: 'acceptable', label: 'مقبول' },
  { id: 'special', label: 'تقييم خاص' },
];

type TemplateItem = { title: string; text: string };
type TemplateGroups = Partial<Record<ReportRating, TemplateItem[]>>;

function build(prefix: string, groups: TemplateGroups): SixWeekTemplate[] {
  return (Object.keys(groups) as ReportRating[]).flatMap((level) =>
    (groups[level] ?? []).map((item, index) => ({
      id: `${prefix}_${level}_${index + 1}`,
      level,
      title: item.title,
      text: item.text,
    }))
  );
}

